# Константы логистики
TRUCK_LENGTH_M = 13.0          # длина фуры, м (как в Excel-эталоне)
TRUCK_MAX_WEIGHT_KG = 20000.0  # норма веса на фуру, кг


class PalletCalculator:
    """Считает паллеты для спецификации."""

    def __init__(self, data_provider):
        self.data_provider = data_provider

    # ==================================================================
    # ПРАВИЛО ПАЛЛЕТЫ ПО ГАБАРИТАМ
    # ==================================================================

    @staticmethod
    def get_pallet_info(
        rad_type: str, height: int, length: int,
    ) -> Tuple[Optional[int], Optional[str]]:
        """
        Возвращает (на_паллете, размер_паллеты) или (None, None),
        если правило не найдено.

        Args:
            rad_type: "10" / "11" / "20" / "21" / "22" / "30" / "33"
            height:   300 / 400 / 500 / 600 / 900
            length:   400 … 3000
        """
        rt = str(rad_type).strip()

        for (t, h, lmin, lmax, qty, size) in PALLET_RULES:
            if t == rt and h == height and lmin <= length <= lmax:
                return qty, size

        return None, None

    @staticmethod
    def is_approximate(rad_type: str, height: int, length: int) -> bool:
        """
        True, если правило для этого радиатора приблизительное
        (длина > 2000 мм).
        """
        if length > 2000:
            return True
        return False

    @staticmethod
    def get_pallet_weight(size: Optional[str]) -> float:
        """
        Вес пустой паллеты. Для всех размеров — 15 кг
        (как в исходном Excel-файле логиста).
        """
        return PALLET_WEIGHT_KG

    # ==================================================================
    # ГАБАРИТЫ ИЗ НАИМЕНОВАНИЯ
    # ==================================================================

    @staticmethod
    def _extract_params_from_name(
        name: str,
    ) -> Tuple[Optional[str], Optional[int], Optional[int]]:
        """
        Извлекает из наименования тип, высоту, длину.

        Наименование вида:
            'Радиатор LaggarTT Classic K-Profil 22/500/400'
            'Радиатор LaggarTT Ventil Hygiene (HV) 10/300/400 ra'

        Returns:
            (rad_type, height, length) или (None, None, None).
        """
        import re

        height = None
        length = None
        rad_type = None

        parts = name.split('/')
        if len(parts) >= 3:
            try:
                lm = re.search(r'(\d{3,4})', parts[-1])
                if lm:
                    length = int(lm.group(1))
                hm = re.search(r'(\d{3,4})', parts[-2])
                if hm:
                    height = int(hm.group(1))
                for p in reversed(parts[:-2]):
                    tm = re.search(r'(\d{2})', p)
                    if tm:
                        rad_type = tm.group(1)
                        break
            except (ValueError, IndexError):
                pass

        if rad_type not in ("10", "11", "20", "21", "22", "30", "33"):
            rad_type = None
        if height not in (300, 400, 500, 600, 900):
            height = None
        if length is None or not (400 <= length <= 3000):
            length = None

        return rad_type, height, length

    # ==================================================================
    # РАСЧЁТ ДЛЯ СПЕЦИФИКАЦИИ
    # ==================================================================

    def calculate_for_spec(self, spec_data: pd.DataFrame) -> pd.DataFrame:
        """
        Принимает DataFrame спецификации (только радиаторы, без кронштейнов),
        возвращает новый DataFrame с колонками:

            №, Артикул, Наименование, Кол-во,
            Длина, мм,
            На паллете, шт,
            Паллет, шт,
            Вес 1, кг,
            Вес общий, кг,
            Вес паллет, кг,
            Вес с паллетами, кг

        Паллет, шт — дробное число (как в Excel-эталоне), без округления.
        """
        rows: List[Dict] = []

        for idx, (_, row) in enumerate(spec_data.iterrows(), start=1):
            name = str(row.get("Наименование", ""))
            if "Кронштейн" in name:
                continue

            try:
                qty = int(row.get("Кол-во", 0))
            except (ValueError, TypeError):
                qty = 0
            if qty <= 0:
                continue

            art = str(row.get("Артикул", "")).strip()

            rad_type, height, length = self._extract_params_from_name(name)

            on_pallet = None
            pallet_size = None
            pallets_count = 0.0
            weight_1 = 0.0

            if rad_type is not None and height is not None and length is not None:
                on_pallet, pallet_size = self.get_pallet_info(
                    rad_type, height, length
                )
                if on_pallet and on_pallet > 0:
                    # Дробное количество паллет, как в Excel
                    pallets_count = round(qty / on_pallet, 2)

            # Вес 1 радиатора
            found = (
                self.data_provider.find_by_article(art)
                if self.data_provider else None
            )
            if found is not None:
                try:
                    weight_1 = float(found.get("Вес, кг", 0) or 0)
                except (ValueError, TypeError):
                    weight_1 = 0.0

            weight_total = round(weight_1 * qty, 2)
            pallet_weight_1 = self.get_pallet_weight(pallet_size)
            weight_pallets = round(pallet_weight_1 * pallets_count, 2)
            weight_with_pallets = round(weight_total + weight_pallets, 2)

            rows.append({
                "№": idx,
                "Артикул": art,
                "Наименование": name,
                "Кол-во": qty,
                "Длина, мм": length if length is not None else "",
                "На паллете, шт": on_pallet if on_pallet else "",
                "Паллет, шт": pallets_count,
                "Вес 1, кг": round(weight_1, 2),
                "Вес общий, кг": weight_total,
                "Вес паллет, кг": weight_pallets,
                "Вес с паллетами, кг": weight_with_pallets,
            })

        return pd.DataFrame(rows)

    # ==================================================================
    # ИТОГИ (дробные — как и раньше)
    # ==================================================================

    def calculate_totals(self, calculated_df: pd.DataFrame) -> Dict:
        """
        Принимает DataFrame из `calculate_for_spec`, возвращает словарь:

            {
                "pallets_short":  ...,   # дробное, сумма
                "pallets_long":   ...,   # дробное, сумма
                "floor_meters":   ...,   # целое
                "trucks":         ...,   # дробное
                "total_weight_kg": ...,
                "weight_per_truck_kg": ...,
            }

        Округление паллет вверх делается НЕ здесь, а в excel_writer.
        """
        import math

        pallets_short = 0.0
        pallets_long = 0.0
        total_weight = 0.0

        for _, row in calculated_df.iterrows():
            try:
                pallets_count = float(row.get("Паллет, шт", 0) or 0)
            except (ValueError, TypeError):
                pallets_count = 0.0

            length = row.get("Длина, мм", "")

            if pallets_count > 0:
                try:
                    length_int = int(length)
                except (ValueError, TypeError):
                    length_int = 0

                if 0 < length_int <= 1200:
                    pallets_short += pallets_count
                elif length_int > 1200:
                    pallets_long += pallets_count

            try:
                total_weight += float(row.get("Вес с паллетами, кг", 0) or 0)
            except (ValueError, TypeError):
                pass

        floor_meters = math.ceil(pallets_short / 2.0) + math.ceil(pallets_long)

        if floor_meters > 0:
            trucks = round(floor_meters / TRUCK_LENGTH_M, 2)
        else:
            trucks = 0.0

        if trucks > 0:
            trucks_rounded = math.ceil(trucks)
            weight_per_truck = total_weight / trucks_rounded
        else:
            weight_per_truck = 0.0

        return {
            "pallets_short": round(pallets_short, 2),
            "pallets_long": round(pallets_long, 2),
            "floor_meters": floor_meters,
            "trucks": trucks,
            "total_weight_kg": round(total_weight, 2),
            "weight_per_truck_kg": round(weight_per_truck, 2),
        }