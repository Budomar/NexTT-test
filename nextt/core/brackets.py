    @classmethod
    def _get_connection_group(cls, connection: str) -> str:
        """
        Определяет группу подключения для подбора кронштейнов.

        Args:
            connection: строка подключения из матрицы радиатора

        Returns:
            "VK_K" — для старых радиаторов (VK-правое, VK-левое, K-боковое)
            "HV_H" — для новых гигиенических радиаторов (HV-правое, HV-левое, H-боковое)
        """
        if connection in ["VK-правое", "VK-левое", "K-боковое"]:
            return "VK_K"
        elif connection in ["HV-правое", "HV-левое", "H-боковое"]:
            return "HV_H"
        else:
            # По умолчанию — старая группа
            logger.warning(f"Неизвестное подключение: {connection}, используется VK_K")
            return "VK_K"

