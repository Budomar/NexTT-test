    @classmethod
    def _find_rule(
        cls,
        rules: List[BracketRule],
        rad_type: str,
        length: int,
        height: int,
    ) -> Optional[BracketRule]:
        """
        Находит подходящее правило в списке.

        Args:
            rules: список правил
            rad_type: тип радиатора
            length: длина радиатора в мм
            height: высота радиатора в мм

        Returns:
            Подходящее правило или None
        """
        for rule in rules:
            # Проверяем тип
            if rad_type not in rule.types:
                continue

            # Проверяем длину
            if not (rule.length_min <= length <= rule.length_max):
                continue

            # Проверяем высоту
            if not (rule.height_min <= height <= rule.height_max):
                continue

            return rule

        return None

