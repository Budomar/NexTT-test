    @classmethod
    def calculate(
        cls,
        radiator_type: str,
        length: int,
        height: int,
        bracket_type: str,
        connection: str = "VK-правое",
        quantity: int = 1,
    ) -> List[Tuple[str, int]]:
        """
        Рассчитывает кронштейны для одного типоразмера радиатора.

        Args:
            radiator_type: тип радиатора ("10", "11", "20", "21", "22", "30", "33")
            length: длина радиатора в мм
            height: высота радиатора в мм
            bracket_type: "Настенные кронштейны", "Напольные кронштейны" или "Без кронштейнов"
            connection: подключение радиатора (для определения группы)
            quantity: количество радиаторов

        Returns:
            Список кортежей (артикул_кронштейна, количество)
        """
        if bracket_type == "Без кронштейнов":
            return []

        # Определяем группу подключения
        conn_group = cls._get_connection_group(connection)

        # Определяем тип монтажа
        if bracket_type == "Настенные кронштейны":
            mount_type = "настенный"
        elif bracket_type == "Напольные кронштейны":
            mount_type = "напольный"
        else:
            return []

        # Выбираем список правил в зависимости от группы и монтажа
        if conn_group == "VK_K":
            if mount_type == "настенный":
                rules = cls.WALL_VK_K_RULES
            else:
                rules = cls.FLOOR_VK_K_RULES
        else:  # HV_H
            if mount_type == "настенный":
                rules = cls.WALL_HV_H_RULES
            else:
                rules = cls.FLOOR_HV_H_RULES

        # Находим все подходящие правила
        matching_rules = []
        for rule in rules:
            if radiator_type in rule.types:
                if rule.length_min <= length <= rule.length_max:
                    if rule.height_min <= height <= rule.height_max:
                        matching_rules.append(rule)

        if not matching_rules:
            logger.debug(
                f"Не найдены кронштейны для: группа={conn_group}, "
                f"тип={radiator_type}, длина={length}, высота={height}, монтаж={mount_type}"
            )
            return []

        # Собираем результат
        result = []
        for rule in matching_rules:
            result.append((rule.article, rule.qty * quantity))

        return result


