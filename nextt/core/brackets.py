    @classmethod
    def calculate_for_manual(
        cls,
        radiator_type: str,
        length: int,
        height: int,
        bracket_type: str,
        connection: str = "VK-правое",
        quantity: int = 1,
    ) -> List[Tuple[str, int]]:
        """
        Подбор кронштейнов для ручного выбора.
        Использует список MANUAL_COMPATIBILITY_RULES.
        В отличие от calculate(), видит ВСЕ кронштейны, включая те,
        которых нет в автоматической матрице.

        Args:
            radiator_type: тип радиатора
            length: длина радиатора в мм
            height: высота радиатора в мм
            bracket_type: "Настенные кронштейны", "Напольные кронштейны" или "Без кронштейнов"
            connection: подключение радиатора
            quantity: количество радиаторов

        Returns:
            Список кортежей (артикул_кронштейна, количество)
        """
        if bracket_type == "Без кронштейнов":
            return []

        # Определяем группу подключения
        conn_group = cls._get_connection_group(connection)

        # Определяем тип монтажа
        if bracket_type == "Настенные кронштейны":
            mount_type = "настенный"
        elif bracket_type == "Напольные кронштейны":
            mount_type = "напольный"
        else:
            return []

        # Ищем подходящие правила в общем списке
        result = []
        for rule in cls.MANUAL_COMPATIBILITY_RULES:
            if rule.connection_group != conn_group:
                continue
            if rule.mount_type != mount_type:
                continue
            if radiator_type not in rule.types:
                continue
            if not (rule.length_min <= length <= rule.length_max):
                continue
            if not (rule.height_min <= height <= rule.height_max):
                continue

            result.append((rule.article, rule.qty * quantity))

        return result
